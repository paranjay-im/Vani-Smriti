// Neo4j export: the same context graph as CSV + Cypher, for LOAD CSV into Neo4j / Aura.
// Default scope is the sample users' neighbourhoods (fits Aura Free); --all exports everything.
import fs from "node:fs";
import path from "node:path";
import { toCsv } from "./csv.js";
import { OUT_DIR } from "./config.js";

const TIER_LABEL = { long_term: "LongTerm", short_term: "ShortTerm", reasoning: "Reasoning" };
const LONG = new Set(["Buyer", "Seller", "Category", "Product", "Mcat", "Employee"]);

function select(g, sellers, buyers) {
  const ids = new Set();
  const addOwned = (map, key) => { for (const list of map.get(key)?.values() || []) for (const id of list) ids.add(id); };
  for (const s of sellers) { ids.add(`S:${s}`); addOwned(g.byGlid, s); }
  for (const b of buyers) { ids.add(`B:${b}`); addOwned(g.byBuyer, b); }
  for (const id of [...ids]) {
    for (const rels of [g.out.get(id), g.in.get(id)]) for (const set of rels?.values() || []) for (const x of set) if (LONG.has(g.get(x)?.label)) ids.add(x);
  }
  return ids;
}

export function exportNeo4j(g, { sellers = [], buyers = [], all = false } = {}) {
  const dir = path.join(OUT_DIR, "neo4j");
  fs.rmSync(dir, { recursive: true, force: true });
  fs.mkdirSync(dir, { recursive: true });
  const ids = all ? null : select(g, sellers, buyers);
  const keep = (id) => !ids || ids.has(id);
  const byLabel = new Map();
  for (const n of g.nodes.values()) {
    if (!keep(n.id)) continue;
    if (!byLabel.has(n.label)) byLabel.set(n.label, []);
    byLabel.get(n.label).push({ id: n.id, tier: n.tier, glid: n.glid, buyer: n.buyer, ts: n.ts, ...n.props });
  }
  const cypher = ["// Generated by context_layer. Copy the CSVs into Neo4j's import/ folder, then run this file.", "CREATE CONSTRAINT node_id IF NOT EXISTS FOR (n:Node) REQUIRE n.id IS UNIQUE;", ""];
  let nNodes = 0;
  for (const [label, rows] of byLabel) {
    const cols = [...new Set(rows.flatMap((r) => Object.keys(r)))];
    fs.writeFileSync(path.join(dir, `nodes_${label}.csv`), toCsv(cols, rows));
    nNodes += rows.length;
    const tier = TIER_LABEL[rows[0].tier];
    cypher.push(`LOAD CSV WITH HEADERS FROM 'file:///nodes_${label}.csv' AS row CALL { WITH row MERGE (n:Node {id: row.id}) SET n += row, n:${label}, n:${tier} } IN TRANSACTIONS OF 5000 ROWS;`);
  }
  const byRel = new Map();
  for (const [src, rel, dst] of g.edges()) {
    if (!keep(src) || !keep(dst) || !g.get(src) || !g.get(dst)) continue;
    if (!byRel.has(rel)) byRel.set(rel, []);
    byRel.get(rel).push({ src, dst });
  }
  cypher.push("");
  let nRels = 0;
  for (const [rel, rows] of byRel) {
    fs.writeFileSync(path.join(dir, `rels_${rel}.csv`), toCsv(["src", "dst"], rows));
    nRels += rows.length;
    cypher.push(`LOAD CSV WITH HEADERS FROM 'file:///rels_${rel}.csv' AS row CALL { WITH row MATCH (a:Node {id: row.src}) MATCH (b:Node {id: row.dst}) MERGE (a)-[:${rel}]->(b) } IN TRANSACTIONS OF 5000 ROWS;`);
  }
  fs.writeFileSync(path.join(dir, "load.cypher"), cypher.join("\n") + "\n");
  fs.writeFileSync(path.join(dir, "queries.cypher"), QUERIES);
  return { dir, nodes: nNodes, rels: nRels, labels: byLabel.size, relTypes: byRel.size };
}

const QUERIES = `// Example queries over the exported context graph ($glid = a seller GLID as a string).

// 1. Reasoning memory: active facts about a seller, with the interaction each came from.
MATCH (f:Fact)-[:ABOUT]->(:Seller {glid: $glid})
OPTIONAL MATCH (f)-[:DERIVED_FROM]->(src)
RETURN f.type, f.ts, f.evidence, labels(src)[0] AS source, src.ts
ORDER BY f.ts DESC;

// 2. Short-term memory: the cross-channel timeline for a seller.
MATCH (i:ShortTerm {glid: $glid})
WHERE NOT i:BotTurn AND NOT i:ChatTurn
RETURN labels(i)[0] AS what, i.ts, coalesce(i.summary, i.product, i.disposition, i.status) AS detail
ORDER BY i.ts DESC LIMIT 25;

// 3. Open loop: buyers waiting on a seller (enquiry with no seller message).
MATCH (b:Buyer)-[:SENT]->(e:Enquiry)-[:TO]->(:Seller {glid: $glid})
WHERE NOT EXISTS { MATCH (e)-[:HAS_MESSAGE]->(m:EnquiryMessage {from: 'seller'}) }
RETURN e.ts, e.product, b.city ORDER BY e.ts DESC LIMIT 10;

// 4. Cross-channel link: buyer calls that turned into enquiries.
MATCH (c:BuyerCall)-[:LED_TO]->(e:Enquiry)-[:TO]->(:Seller {glid: $glid})
RETURN c.ts, c.talk, e.ts, e.product;

// 5. Explainability: why did VANI skip a question or suppress a call?
MATCH (d:Decision {glid: $glid})
OPTIONAL MATCH (d)-[:USED]->(f:Fact)-[:DERIVED_FROM]->(src)
RETURN d.ts, d.action, d.question, d.reason, f.type, labels(src)[0] AS evidence_from, src.ts
ORDER BY d.ts;
`;
